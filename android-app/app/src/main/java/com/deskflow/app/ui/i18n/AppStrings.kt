package com.deskflow.app.ui.i18n

/**
 * Runtime language bridge for UI strings that are written inline in Compose
 * code instead of string resources.
 *
 * The old code hardcoded Vietnamese text in ~200 places, so switching the app
 * to English only changed the `strings.xml` entries while every inline label
 * stayed Vietnamese. Screen composables are keyed on the selected language, so
 * calling [t] during recomposition re-evaluates it with the new value.
 */
object AppStrings {
    @Volatile
    var language: String = "vi"

    fun t(vi: String): String = if (language == "vi") vi else (ENGLISH[vi] ?: vi)

    /**
     * For strings that contain Kotlin interpolation: pass both the Vietnamese
     * and the English template so `${...}` keeps working after substitution.
     */
    fun pick(vi: String, en: String): String = if (language == "vi") vi else en

    /**
     * For strings built with Kotlin interpolation (e.g. "Đã chuyển màu đèn: $hex"):
     * the value is already substituted, so translate the static Vietnamese
     * fragments inside it and keep the interpolated data untouched.
     */
    fun tpl(text: String): String {
        if (language == "vi") return text
        var out = text
        for ((vi, en) in FRAGMENTS) {
            out = out.replace(vi, en)
        }
        return out
    }
}

